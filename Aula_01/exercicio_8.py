primeiro_numero = float(input("Insira o primeiro número: "))
segundo_numero = float(input("Insira o segundo número: "))

print(f"Resultado da adição: {primeiro_numero + segundo_numero}")

print(f"Resultado da subtração: {primeiro_numero - segundo_numero}")

print(f"Resultado da multiplicação: {primeiro_numero * segundo_numero}")

print(f"Resultado da divisão: {primeiro_numero / segundo_numero}")

print(f"Resultado do resto da divisão: {primeiro_numero % segundo_numero}")

print(f"Resultado da potência do primeiro número elevado ao segundo: {primeiro_numero ** segundo_numero}")